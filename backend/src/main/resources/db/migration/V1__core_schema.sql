-- TheBridge V1 — core schema (Phase 1 tables, ready for later phases)

create table users (
    id             bigint generated by default as identity primary key,
    email          varchar(255) not null unique,
    password_hash  varchar(255) not null,
    display_name   varchar(100) not null,
    timezone       varchar(64)  not null default 'UTC',
    day_start_hour smallint     not null default 4 check (day_start_hour between 0 and 12),
    created_at     timestamptz  not null default now()
);

create table diary_entries (
    id             bigint generated by default as identity primary key,
    user_id        bigint not null references users (id) on delete cascade,
    entry_date     date   not null,
    mood           smallint check (mood between 1 and 5),
    energy         smallint check (energy between 1 and 5),
    morning_intent text,
    evening_review text,
    body           text,
    tags           text[] not null default '{}',
    created_at     timestamptz not null default now(),
    updated_at     timestamptz not null default now(),
    unique (user_id, entry_date)
);

create table thoughts (
    id          bigint generated by default as identity primary key,
    user_id     bigint not null references users (id) on delete cascade,
    content     text not null,
    kind        varchar(16) not null default 'worry'
                check (kind in ('worry', 'idea', 'gratitude', 'task')),
    status      varchar(16) not null default 'open'
                check (status in ('open', 'released')),
    reframe     text,
    created_at  timestamptz not null default now(),
    released_at timestamptz
);

create index idx_thoughts_user_created on thoughts (user_id, created_at desc);

create table exercises (
    id               bigint generated by default as identity primary key,
    slug             varchar(64)  not null unique,
    name             varchar(120) not null,
    type             varchar(32)  not null
                     check (type in ('breathing', 'grounding', 'bodyscan', 'pmr')),
    pattern          jsonb,
    duration_options smallint[]   not null default '{2,5}',
    description      text,
    sos              boolean      not null default false,
    sort_order       integer      not null default 0
);

create table exercise_sessions (
    id            bigint generated by default as identity primary key,
    user_id       bigint not null references users (id) on delete cascade,
    exercise_id   bigint not null references exercises (id),
    kind          varchar(16) not null default 'regular'
                  check (kind in ('regular', 'sos')),
    started_at    timestamptz not null,
    duration_sec  integer not null check (duration_sec >= 0),
    completed     boolean not null default false,
    gems_awarded  smallint not null default 0,
    created_at    timestamptz not null default now()
);

create index idx_sessions_user_started on exercise_sessions (user_id, started_at desc);

-- Append-only ledger: gem balance is derived (SUM(delta)), never a mutable counter.
create table gem_ledger (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    delta      integer not null check (delta <> 0),
    reason     varchar(64) not null,
    ref_type   varchar(32),
    ref_id     bigint,
    created_at timestamptz not null default now()
);

create index idx_ledger_user_created on gem_ledger (user_id, created_at desc);

create table sleep_logs (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    sleep_date date not null,          -- the day you woke up
    bed_time   timestamptz not null,
    wake_time  timestamptz not null,
    quality    smallint check (quality between 1 and 5),
    delay_note text,
    created_at timestamptz not null default now(),
    unique (user_id, sleep_date)
);

create table meals (
    id             bigint generated by default as identity primary key,
    user_id        bigint not null references users (id) on delete cascade,
    eaten_at       timestamptz not null,
    meal_type      varchar(16) not null
                   check (meal_type in ('breakfast', 'lunch', 'dinner', 'snack')),
    description    text,
    home_cooked    boolean,
    hunger_before  smallint check (hunger_before between 1 and 5),
    hunger_after   smallint check (hunger_after between 1 and 5),
    created_at     timestamptz not null default now()
);

create index idx_meals_user_eaten on meals (user_id, eaten_at desc);

create table weight_entries (
    id          bigint generated by default as identity primary key,
    user_id     bigint not null references users (id) on delete cascade,
    measured_at timestamptz not null default now(),
    weight_kg   numeric(5, 2) not null check (weight_kg > 0),
    note        text,
    created_at  timestamptz not null default now()
);

create index idx_weight_user_measured on weight_entries (user_id, measured_at desc);
