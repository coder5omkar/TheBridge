-- The rhythm: user-defined recurring practices and their daily check-off logs.

create table habits (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    name       varchar(100) not null,
    emoji      varchar(8) not null default '✅',
    part       varchar(16) not null default 'anytime'
               check (part in ('morning', 'afternoon', 'evening', 'anytime')),
    sort_order integer not null default 0,
    active     boolean not null default true,
    created_at timestamptz not null default now()
);

create table habit_logs (
    id         bigint generated by default as identity primary key,
    user_id    bigint not null references users (id) on delete cascade,
    habit_id   bigint not null references habits (id) on delete cascade,
    log_date   date not null,
    created_at timestamptz not null default now(),
    unique (habit_id, log_date)
);

create index idx_habit_logs_user_date on habit_logs (user_id, log_date);
